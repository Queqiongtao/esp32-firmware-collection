#!/usr/bin/env python3
"""Explicitly regenerate the checked-in 88px RGB565 watch-face previews.

Run after ./tools/preview/run.sh (which never rewrites tracked resources).
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
FACES = [
    ("minimal", "Minimal"), ("segment", "Segment"), ("analog", "Analog"),
    ("m5_classic", "Classic"), ("m5_simple", "Simple"),
    ("m5_big_number", "Big Number"), ("m5_number_flow", "Number Flow"),
    ("dot_matrix", "Dot Matrix"),
]
SIZE = 88


def main():
    parts = ['// Generated by tools/preview/generate_thumbnails.py. Do not edit.\n'
             '#include "clock_theme_previews.h"\n']
    for theme, _ in FACES:
        path = ROOT / "tools/preview/out/ppm" / f"{theme}_10-08-35.ppm"
        image = Image.open(path).convert("RGB").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
        mask = Image.new("L", (SIZE, SIZE))
        ImageDraw.Draw(mask).ellipse((0, 0, SIZE - 1, SIZE - 1), fill=255)
        image = Image.composite(image, Image.new("RGB", image.size), mask)
        data = []
        rgb = image.tobytes()
        for r, g, b in zip(rgb[0::3], rgb[1::3], rgb[2::3]):
            pixel = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            data.extend((pixel & 255, pixel >> 8))
        parts.append(f"static const uint8_t {theme}_pixels[] = {{")
        parts.extend("    " + ",".join(f"0x{x:02x}" for x in data[i:i+24]) + ","
                     for i in range(0, len(data), 24))
        parts.append("};")
        parts.append(f"""static const lv_image_dsc_t {theme}_preview = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,
                .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 2}}},
    .data_size = sizeof({theme}_pixels), .data = {theme}_pixels,
}};""")
    parts.append("const clock_settings_menu_theme_t g_clock_theme_previews[8] = {")
    parts.extend(f'    {{"{name}", &{theme}_preview}},' for theme, name in FACES)
    parts.append("};\n")
    output = ROOT / "main/clock_theme_previews.c"
    output.write_text("\n".join(parts))
    print(f"Generated {output}: {len(FACES) * SIZE * SIZE * 2} image bytes")


if __name__ == "__main__":
    main()
