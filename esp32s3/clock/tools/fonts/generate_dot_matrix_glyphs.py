#!/usr/bin/env python3
"""Sample Ubuntu Sans into fixed 15x25 dot masks; no font needed at runtime."""

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
WIDTH, HEIGHT = 15, 25
SUPERSAMPLE = 32
FONT_SIZE = 200
AXES = [75, 750]  # Ubuntu Sans: width, weight
THRESHOLD = 112


def generate(font_path):
    font = ImageFont.truetype(str(font_path), FONT_SIZE)
    font.set_variation_by_axes(AXES)
    # Derive one scale from all ten glyphs. Every cell uses the same baseline,
    # font size and advance centering, so narrow digits retain their proportions.
    boxes = [font.getbbox(str(digit), anchor="ls") for digit in range(10)]
    top = min(box[1] for box in boxes)
    bottom = max(box[3] for box in boxes)
    advance = max(font.getlength(str(digit)) for digit in range(10))
    scale = min(WIDTH / advance, HEIGHT / (bottom - top))
    font = ImageFont.truetype(str(font_path), round(FONT_SIZE * scale * SUPERSAMPLE))
    font.set_variation_by_axes(AXES)
    boxes = [font.getbbox(str(digit), anchor="ls") for digit in range(10)]
    top = min(box[1] for box in boxes)
    bottom = max(box[3] for box in boxes)
    baseline = (HEIGHT * SUPERSAMPLE - (bottom - top)) / 2 - top
    masks = []
    for digit in range(10):
        cell = Image.new("L", (WIDTH * SUPERSAMPLE, HEIGHT * SUPERSAMPLE))
        x = (cell.width - font.getlength(str(digit))) / 2
        ImageDraw.Draw(cell).text((x, baseline), str(digit), font=font, fill=255, anchor="ls")
        sampled = cell.resize((WIDTH, HEIGHT), Image.Resampling.BOX)
        masks.append([
            sum(1 << (WIDTH - col - 1) for col in range(WIDTH)
                if sampled.getpixel((col, row)) >= THRESHOLD)
            for row in range(HEIGHT)
        ])
    return masks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path,
                        default=Path("/usr/share/fonts/truetype/ubuntu/UbuntuSans[wdth,wght].ttf"))
    parser.add_argument("--output", type=Path, default=ROOT / "main/dot_matrix_glyphs.h")
    args = parser.parse_args()
    masks = generate(args.font)
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    lines = [
        "// Generated by tools/fonts/generate_dot_matrix_glyphs.py. Do not edit.",
        "// Source: Ubuntu Sans variable, Ubuntu font package (Ubuntu Font Licence 1.0).",
        "// Copyright 2011, 2022, 2023 Canonical Ltd. See tools/fonts/ubuntu-font-licence.txt.",
        "// Ubuntu Sans derivative Clock Dot Matrix (15x25 digit subset).",
        f"// Font: {args.font.name}; SHA-256: {digest}",
        f"// Axes: wdth={AXES[0]}, wght={AXES[1]}; grid={WIDTH}x{HEIGHT}; coverage >= {THRESHOLD}/255.",
        f"// Shared scale/baseline; {SUPERSAMPLE}x area sampling. Bit 14 is the leftmost dot.",
        "#pragma once", "", "#include <cstdint>", "",
        "namespace dot_matrix_glyphs {",
        f"constexpr int kWidth = {WIDTH};",
        f"constexpr int kHeight = {HEIGHT};",
        "constexpr uint16_t kDigits[10][kHeight] = {",
    ]
    for digit, rows in enumerate(masks):
        lines.append(f"    {{ // {digit}")
        for offset in range(0, HEIGHT, 5):
            lines.append("        " + ", ".join(f"0x{row:04X}" for row in rows[offset:offset + 5]) + ",")
        lines.append("    },")
    lines.extend(["};", "} // namespace dot_matrix_glyphs", ""])
    args.output.write_text("\n".join(lines))
    print(f"Generated {args.output}: {len(masks)} glyphs, {WIDTH}x{HEIGHT}, {len(masks) * HEIGHT * 2} bytes")


if __name__ == "__main__":
    main()
